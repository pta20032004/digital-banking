package com.tony.demo.infra.init;

import java.time.LocalDate;

import org.springframework.beans.factory.annotation.Value;
import org.springframework.boot.CommandLineRunner;
import org.springframework.security.crypto.password.PasswordEncoder;
import org.springframework.stereotype.Component;
import org.springframework.transaction.annotation.Transactional;

import com.tony.demo.modules.user.domain.User;
import com.tony.demo.modules.user.domain.UserRepository;
import com.tony.demo.modules.user.domain.UserStatus;

import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;

@Component
@RequiredArgsConstructor
@Slf4j
public class FakeCustomerSeeder implements CommandLineRunner {

    private final UserRepository userRepository;
    private final PasswordEncoder passwordEncoder;

    @Value("${fake.customer.username}")
    private String username;

    @Value("${fake.customer.fullName}")
    private String fullName;

    @Value("${fake.customer.dob}")
    private String dob;

    @Value("${fake.customer.email}")
    private String email;

    @Value("${fake.customer.password}")
    private String password;

    @Value("${fake.customer.phone}")
    private String phone;

    @Value("${fake.customer.identity}")
    private String identity;

    @Value("${fake.customer.kycStatus}")
    private String kycStatus;

    @Override
    @Transactional
    public void run(String... args) throws Exception {
        if (!userRepository.existsByUsername(username)) {
            log.info("Inserting fake customer {} from environment variables...", username);
            User user = User.builder()
                    .username(username)
                    .fullName(fullName.replace("\"", "")) // Clean up quotes if present
                    .dateOfBirth(LocalDate.parse(dob))
                    .email(email)
                    .password(passwordEncoder.encode(password)) // Hash password
                    .phoneNumber(phone)
                    .identityNumber(identity)
                    .kycStatus(UserStatus.valueOf(kycStatus.toUpperCase()))
                    .build();
            // id, public_id are generated by sequences and BaseEntity automatically
            userRepository.save(user);
            log.info("Fake customer {} inserted successfully.", username);
        } else {
            log.info("Fake customer {} already exists in database.", username);
        }
    }
}
